//! Точка входа приложения CRM.
//!
//! Здесь поднимается встроенный сервер и создаётся окно, которое смотрит на
//! него. Сервер решает главную задачу: фронтенд ходит на относительные пути
//! (`/api/...`), и чтобы не переписывать их в 320 местах, приложение
//! предоставляет и статику, и API с одного адреса — как это делает nginx
//! на проде.

mod notifications;
mod proxy;

use tauri::{Manager, WebviewUrl, WebviewWindowBuilder};

/// Масштаб интерфейса: 0.8 = 80%. Меняйте здесь — больше нигде править не надо.
const ZOOM: f64 = 0.8;

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        // Нативные уведомления macOS: работают, даже когда окно свёрнуто
        // или скрыто в трее, — то, чего не умеет веб-версия.
        .plugin(tauri_plugin_notification::init())
        .setup(|app| {
            // Сервер поднимаем до окна: адрес нужен уже при создании окна,
            // а не после. Здесь же узнаём настоящий порт, если основной занят.
            let start_url = match proxy::start() {
                Ok(handle) => {
                    // Открываем сразу CRM, а не витрину магазина. На корне
                    // живёт клиентская часть с обязательной авторизацией через
                    // Telegram: в админском приложении этот гейт только мешает,
                    // а CRM доступна по /admin, куда он по своему условию
                    // не показывается.
                    format!("http://127.0.0.1:{}/admin", handle.port)
                }
                Err(e) => {
                    eprintln!("[crm] сервер приложения не запустился: {e}");
                    // Показываем страницу с объяснением вместо пустого окна:
                    // молчаливо серый экран — худший вариант.
                    format!("data:text/html;charset=utf-8,{}", error_page(&e))
                }
            };
            println!("[crm] окно открывается на {start_url}");

            // Адрес задаём прямо здесь, а не навигацией после создания окна:
            // навигация в этот момент иногда терялась, и окно оставалось на
            // стартовой странице, показывая чужой гейт авторизации.
            let parsed: tauri::Url = start_url
                .parse()
                .map_err(|e| format!("неверный адрес окна: {e}"))?;
            WebviewWindowBuilder::new(app, "main", WebviewUrl::External(parsed))
                .title("NAVALIVAY CRM")
                .inner_size(1440.0, 900.0)
                .min_inner_size(1024.0, 700.0)
                .resizable(true)
                // Перехват уведомлений: браузерный Notification не работает,
                // когда окно неактивно, а фоновая доставка — то, ради чего
                // затевалось нативное приложение. Скрипт выполняется до
                // загрузки страницы, поэтому CRM сразу видит подмену.
                .initialization_script(notifications::NOTIFICATION_BRIDGE)
                .build()?;

            // Масштаб интерфейса. На большом экране CRM в 100% выглядит
            // крупно: видно мало строк, а списки заказов и товаров длинные.
            // 80% показывает примерно вдвое больше без потери читаемости —
            // при системном рендеринге macOS текст остаётся резким.
            //
            // Ставим после создания окна: на macOS webview должен быть уже
            // готов, иначе масштаб применится не к тому представлению.
            if let Some(window) = app.get_webview_window("main") {
                if let Err(e) = window.set_zoom(ZOOM) {
                    // Масштаб — удобство, а не условие работы: если не применился,
                    // приложение должно открыться обычным, а не упасть.
                    eprintln!("[crm] не удалось задать масштаб {ZOOM}: {e}");
                }
            }

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("ошибка запуска приложения");
}

/// Простая страница-объяснение на случай, если сервер не поднялся.
fn error_page(reason: &str) -> String {
    let message = format!(
        "Внутренний сервер приложения не запустился.\n\n{reason}\n\n\
         Закройте приложение и откройте заново. Если не помогает — \
         перезагрузите компьютер: возможно, порт занят другой копией."
    );
    // data:-адрес требует процентов вместо пробелов и переводов строк.
    message
        .replace('%', "%25")
        .replace(' ', "%20")
        .replace('\n', "%0A")
}
