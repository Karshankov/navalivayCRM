/**
 * Деньги округляем до копеек в момент записи в базу.
 *
 * Средневзвешенная себестоимость и прибыль считаются делением, и без
 * округления в базу попадали числа вида 11.399999999999999. Дальше хвост
 * расползался: себестоимость тянула за собой прибыль заказа, прибыль тянула
 * сумму за день, и на дашборде появлялось 1275.5360149761204. Плюс при каждом
 * пересчёте хвост менялся, поэтому себестоимость «дрожала» после запятой.
 */
export function roundMoney(value) {
  const amount = Number(value);
  if (!Number.isFinite(amount)) return 0;
  // Смещение через exponent защищает от случаев вроде 1.005, где умножение
  // на 100 даёт 100.49999999999999 и Math.round округляет не в ту сторону.
  return Number(`${Math.round(Number(`${amount}e2`))}e-2`);
}

/** Количества на складе целые, но приходят и строками, и дробью. */
export function roundQuantity(value) {
  const amount = Number(value);
  if (!Number.isFinite(amount)) return 0;
  return Math.round(amount);
}
