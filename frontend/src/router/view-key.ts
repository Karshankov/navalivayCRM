/**
 * Ключ для верхнего <RouterView> в App.vue.
 *
 * Зачем отдельный модуль: ключ там стоял `route.fullPath`, а верхний RouterView
 * рисует не весь путь, а только его корневую часть. Из-за этого любое движение
 * ВНУТРИ раздела считалось сменой страницы:
 *
 *   - клик по вкладке админки делает router.push({ path: '/admin',
 *     query: { tab } }) (AdminView.vue, около строки 1751) — fullPath меняется;
 *   - переход между разделами CRM меняет вложенный маршрут /admin/crm/*, а
 *     рисует его вложенный <RouterView> внутри AdminView (AdminView.vue:10).
 *
 * В обоих случаях компонент верхнего уровня остаётся тем же самым, но менялся
 * ключ — и Vue сносил и заново собирал всю админку. Хуже того, старый экземпляр
 * во время ухода остаётся смонтированным и реактивным: он сразу перерисовывался
 * под новый маршрут. Человек видел, как содержимое подменилось ДО того, как
 * началась анимация ухода, а потом уже это подменённое уезжало и возвращалось.
 *
 * Поэтому ключ собирается из того, что верхний RouterView действительно рисует:
 * запись нулевой глубины плюс её собственные параметры. Параметры вложенных
 * записей и строка запроса в ключ не входят — они меняют содержимое вложенного
 * представления, а не верхнего.
 *
 * Что при этом сохраняется: `/p/1` → `/p/2` и `/category/a` → `/category/b`
 * по-прежнему пересобирают экран, потому что `:id` и `:slug` объявлены в самой
 * записи нулевой глубины и входят в ключ.
 */

/** Минимум, который нужен от маршрута. Vue Router отдаёт больше. */
export interface KeyedRoute {
  fullPath: string;
  params: Record<string, unknown>;
  matched: readonly { path: string }[];
}

export function topLevelViewKey(route: KeyedRoute): string {
  const root = route.matched[0];
  // Маршрут без совпадений рисовать нечем, но ключ обязан остаться уникальным.
  if (!root) return route.fullPath;

  // Имена параметров берём из шаблона самой записи: у `/p/:id` это `id`, у
  // `/admin` их нет вовсе. Параметры дочерних записей (`/admin/crm/orders/:id`)
  // в шаблоне корня не встречаются и в ключ не попадают.
  const declared = root.path.match(/:\w+/g) ?? [];
  return [root.path, ...declared.map((name) => String(route.params[name.slice(1)] ?? ""))].join("|");
}
